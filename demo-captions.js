// ---------- Gate de calidad ----------
// La prueba no tiene IG del visitante ni ficha real: el "dato real" del tema
// es su propio spec (tag/headline/subline). El gate valida contra eso:
// muletillas quemadas, CTA, hook, largo, emojis/hashtags, números de promo
// consistentes con el spec, sin claims inventados.
function topicDna(t) {
  const spec = [t.tag, t.headline, t.subline].filter(Boolean).join(' | ');
  return {
    producto_estrella: t.headline || '',
    productos: [t.headline, t.subline].filter(Boolean).join(' | '),
    servicios: [],
    promos_activas: [spec],
  };
}

// Caption final: reemplaza {BIZ}, suma la línea de objetivo y convierte el tono.
function buildFinalCaption(t, { business, tone, goalLine }) {
  let caption = String((t && t.caption) || '').split('{BIZ}').join(business);
  if (goalLine) caption += goalLine;
  if (tone === 'tu') caption = toTu(caption);
  return caption;
}

